// STREAM NOTIFICATIONS - one provider-neutral event contract worn by four visual designs.
//
// A follower, member, donation, gift and raid are data, not states. The state machine only
// owns the shared lifecycle: hidden -> enter -> hold -> exit. queueNotification() is the
// integration seam for a future provider adapter, but this template needs no provider and
// remains fully operable through ordinary SPX fields and the generated control page.

